"""Persistent local accounts and expiring, opaque sessions."""

from __future__ import annotations

import hashlib
import re
import secrets
import sqlite3
import time
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path
from typing import Any

import psycopg
from psycopg.rows import dict_row


class PostgresConnection:
    """Adapt the shared parameterized account queries to PostgreSQL."""

    def __init__(self, connection: psycopg.Connection[dict[str, Any]]) -> None:
        self.connection = connection

    def execute(self, query: str, parameters: Any = None) -> Any:
        return self.connection.execute(query.replace("?", "%s"), parameters)

    def executescript(self, script: str) -> None:
        for statement in script.split(";"):
            if statement.strip():
                self.execute(statement)


SESSION_SECONDS = 8 * 60 * 60


class AuthStore:
    def __init__(self, path: Path | str) -> None:
        self.path = path
        self.postgres = isinstance(path, str) and path.startswith(("postgresql://", "postgres://"))
        if not self.postgres:
            Path(path).parent.mkdir(parents=True, exist_ok=True)
        identity = (
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
            if self.postgres
            else ("INTEGER PRIMARY KEY")
        )
        with self.connect() as db:
            db.executescript(f"""
                CREATE TABLE IF NOT EXISTS users (
                    id {identity}, email TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL, name TEXT NOT NULL DEFAULT '',
                    company TEXT NOT NULL DEFAULT '', username TEXT UNIQUE,
                    job_position TEXT NOT NULL DEFAULT ''
                );
                CREATE TABLE IF NOT EXISTS sessions (
                    token TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
                    expires DOUBLE PRECISION NOT NULL
                );
                CREATE TABLE IF NOT EXISTS login_attempts (
                    email TEXT NOT NULL, attempted DOUBLE PRECISION NOT NULL
                );
                CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);
                CREATE INDEX IF NOT EXISTS attempts_email_time ON login_attempts(email, attempted);
                CREATE TABLE IF NOT EXISTS external_identities (
                    provider TEXT NOT NULL, subject TEXT NOT NULL,
                    user_id BIGINT NOT NULL REFERENCES users(id),
                    PRIMARY KEY(provider, subject), UNIQUE(provider, user_id)
                );
                CREATE TABLE IF NOT EXISTS oauth_states (
                    state TEXT PRIMARY KEY, nonce TEXT NOT NULL, verifier TEXT NOT NULL,
                    link_user BIGINT REFERENCES users(id), expires DOUBLE PRECISION NOT NULL
                );
            """)

    @contextmanager
    def connect(self) -> Iterator[Any]:
        if self.postgres:
            with psycopg.connect(
                str(self.path), row_factory=dict_row, connect_timeout=5
            ) as connection:
                yield PostgresConnection(connection)
        else:
            db = sqlite3.connect(self.path)
            db.row_factory = sqlite3.Row
            db.execute("PRAGMA foreign_keys = ON")
            try:
                with db:
                    yield db
            finally:
                db.close()

    def register(self, data: dict[str, Any]) -> str:
        email = str(data.get("email", "")).strip().lower()
        password = data.get("password", "")
        if len(email) > 254 or not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", email):
            raise ValueError("Enter a valid email address.")
        if not isinstance(password, str) or not 12 <= len(password) <= 128:
            raise ValueError("Use a password between 12 and 128 characters.")
        salt = secrets.token_hex(16)
        digest = hashlib.scrypt(password.encode(), salt=salt.encode(), n=16384, r=8, p=1).hex()
        try:
            with self.connect() as db:
                cursor = db.execute(
                    "INSERT INTO users(email, password) VALUES (?, ?) RETURNING id",
                    (email, salt + ":" + digest),
                )
                user_id = cursor.fetchone()["id"]
        except (sqlite3.IntegrityError, psycopg.IntegrityError) as error:
            raise ValueError("Unable to create account with this email. Try signing in.") from error
        return self.session(user_id)

    def login(self, data: dict[str, Any]) -> str:
        email = str(data.get("email", "")).strip().lower()
        with self.connect() as db:
            db.execute("DELETE FROM login_attempts WHERE attempted < ?", (time.time() - 300,))
            attempts = db.execute(
                "SELECT COUNT(*) AS attempts FROM login_attempts WHERE email = ?", (email,)
            ).fetchone()["attempts"]
            if attempts >= 5:
                raise ValueError("Too many sign-in attempts. Try again in five minutes.")
            db.execute("INSERT INTO login_attempts VALUES (?, ?)", (email, time.time()))
        password = data.get("password", "")
        if not isinstance(password, str) or len(password) > 128:
            raise ValueError("Incorrect email or password.")
        with self.connect() as db:
            user = db.execute("SELECT * FROM users WHERE email = ?", (email,)).fetchone()
        salt, expected = (
            user["password"].split(":")
            if user and ":" in user["password"]
            else ("0" * 32, "0" * 128)
        )
        actual = hashlib.scrypt(password.encode(), salt=salt.encode(), n=16384, r=8, p=1).hex()
        if not secrets.compare_digest(actual, expected) or user is None:
            raise ValueError("Incorrect email or password.")
        with self.connect() as db:
            db.execute("DELETE FROM login_attempts WHERE email = ?", (email,))
        return self.session(user["id"])

    def google_account(self, claims: dict[str, Any], link_user: int | None = None) -> str:
        """Consume verified Google claims; never link accounts by email alone."""
        subject = claims.get("sub")
        email = claims.get("email")
        if (
            not isinstance(subject, str)
            or not 1 <= len(subject) <= 255
            or not isinstance(email, str)
            or claims.get("email_verified") is not True
        ):
            raise ValueError("Google did not provide a verified email address.")
        email = email.strip().lower()
        if len(email) > 254 or not re.fullmatch(r"[^\s@]+@[^\s@]+\.[^\s@]+", email):
            raise ValueError("Google did not provide a valid email address.")
        try:
            with self.connect() as db:
                identity = db.execute(
                    "SELECT user_id FROM external_identities WHERE provider='google' AND subject=?",
                    (subject,),
                ).fetchone()
                if identity:
                    user_id = identity["user_id"]
                    if link_user is not None and link_user != user_id:
                        raise ValueError("This Google account is linked to another account.")
                else:
                    if link_user is not None:
                        if not db.execute(
                            "SELECT id FROM users WHERE id=?", (link_user,)
                        ).fetchone():
                            raise ValueError("Sign in again before connecting Google.")
                        user_id = link_user
                    else:
                        if db.execute("SELECT id FROM users WHERE email=?", (email,)).fetchone():
                            raise ValueError(
                                "An account already uses this email. Sign in with your password, "
                                "open your profile, and choose Connect Google."
                            )
                        user_id = db.execute(
                            "INSERT INTO users(email,password,name) VALUES (?, ?, ?) RETURNING id",
                            (email, "!", str(claims.get("name", ""))[:100]),
                        ).fetchone()["id"]
                    db.execute(
                        "INSERT INTO external_identities VALUES ('google', ?, ?)",
                        (subject, user_id),
                    )
        except (sqlite3.IntegrityError, psycopg.IntegrityError) as error:
            raise ValueError(
                "Unable to connect this Google account. Try signing in again."
            ) from error
        return self.session(user_id)

    def begin_google(self, link_user: int | None = None) -> tuple[str, str, str]:
        state, nonce, verifier = (secrets.token_urlsafe(32) for _ in range(3))
        with self.connect() as db:
            db.execute("DELETE FROM oauth_states WHERE expires <= ?", (time.time(),))
            db.execute(
                "INSERT INTO oauth_states VALUES (?, ?, ?, ?, ?)",
                (
                    hashlib.sha256(state.encode()).hexdigest(),
                    nonce,
                    verifier,
                    link_user,
                    time.time() + 600,
                ),
            )
        return state, nonce, verifier

    def consume_google(self, state: str) -> dict[str, Any]:
        with self.connect() as db:
            row = db.execute(
                "DELETE FROM oauth_states WHERE state=? RETURNING *",
                (hashlib.sha256(state.encode()).hexdigest(),),
            ).fetchone()
        if not row or row["expires"] <= time.time():
            raise ValueError("Google sign-in expired. Please try again.")
        return dict(row)

    def session(self, user_id: int | None) -> str:
        token = secrets.token_urlsafe(32)
        with self.connect() as db:
            db.execute("DELETE FROM sessions WHERE expires <= ?", (time.time(),))
            db.execute(
                "INSERT INTO sessions VALUES (?, ?, ?)",
                (
                    hashlib.sha256(token.encode()).hexdigest(),
                    user_id,
                    time.time() + SESSION_SECONDS,
                ),
            )
        return token

    def user(self, token: str) -> dict[str, Any] | None:
        with self.connect() as db:
            row = db.execute(
                "SELECT users.id, email, name, company, username, job_position, "
                "EXISTS(SELECT 1 FROM external_identities WHERE provider='google' "
                "AND user_id=users.id) AS google_connected FROM users "
                "JOIN sessions ON users.id = sessions.user_id WHERE token = ? AND expires > ?",
                (hashlib.sha256(token.encode()).hexdigest(), time.time()),
            ).fetchone()
        return dict(row) if row else None

    def logout(self, token: str) -> None:
        with self.connect() as db:
            db.execute(
                "DELETE FROM sessions WHERE token = ?",
                (hashlib.sha256(token.encode()).hexdigest(),),
            )

    def profile(self, user_id: int, data: dict[str, Any]) -> None:
        values = []
        for field in ("name", "company", "username", "job_position"):
            value = data.get(field)
            if not isinstance(value, str) or not 1 <= len(value.strip()) <= 100:
                raise ValueError("Complete every profile field (maximum 100 characters each).")
            values.append(value.strip())
        values[2] = values[2].lower()
        if not re.fullmatch(r"[a-z0-9_]{3,30}", values[2]):
            raise ValueError("Username must be 3–30 letters, numbers, or underscores.")
        try:
            with self.connect() as db:
                db.execute(
                    "UPDATE users SET name=?, company=?, username=?, job_position=? WHERE id=?",
                    (*values, user_id),
                )
        except (sqlite3.IntegrityError, psycopg.IntegrityError) as error:
            raise ValueError("This username is already taken.") from error
